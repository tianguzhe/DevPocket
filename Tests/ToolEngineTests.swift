import Foundation

@main
struct ToolEngineTests {
    static func run(_ mode: ToolMode, _ input: String, zone: String = "UTC") throws -> String {
        guard case .text(let text) = try ToolEngine.run(ToolRequest(mode: mode, input: input, timeZoneID: zone)) else {
            fatalError("Expected text output")
        }
        return text
    }
    static func check(_ expression: @autoclosure () throws -> Bool) throws {
        let result = try expression()
        precondition(result)
    }
    static func rejects(_ mode: ToolMode, _ input: String) {
        do {
            _ = try run(mode, input)
            fatalError("Expected rejection: \(mode), \(input.prefix(40))")
        } catch {}
    }
    static func aes(_ mode: ToolMode, _ input: String, _ options: AESOptions = AESOptions()) throws -> String {
        guard case .text(let text) = try ToolEngine.run(ToolRequest(mode: mode, input: input, aes: options)) else {
            fatalError("Expected AES text output")
        }
        return text
    }
    static func rejectsAES(_ input: String, _ options: AESOptions = AESOptions(), mode: ToolMode = .aesDecrypt, message: String) {
        do {
            _ = try aes(mode, input, options)
            fatalError("Expected AES rejection")
        } catch {
            precondition(error.localizedDescription.contains(message), error.localizedDescription)
        }
    }
    static func testAES() throws {
        // Independent fixtures generated by cy-tools' CryptoJS, not by this engine.
        let plaintext = #"{"app":"DevPocket","message":"你好，开发者 👋","offline":true}"#
        let hex = "571765f45cd92759afd597fcae4b620d9ca0e4d91b269f978e4b9c6acb6da5333d2567c8dbc173b8c268d9694143241ecd8afc9daec2e792b5ebf8031019553330226970c3dfb3ee19ad78f6e33afd1e"
        try check(try aes(.aesDecrypt, hex) == plaintext)
        try check(try aes(.aesEncrypt, plaintext) == hex)
        let spaced = hex.uppercased().enumerated().map { ($0.offset % 8 == 0 ? " \n" : "") + String($0.element) }.joined()
        try check(try aes(.aesDecrypt, spaced) == plaintext)
        let base64 = "Vxdl9FzZJ1mv1Zf8rktiDZyg5NkbJp+XjkucasttpTM9JWfI28FzuMJo2WlBQyQezYr8na7C55K16/gDEBlVMzAiaXDD37PuGa149uM6/R4="
        let base64Options = AESOptions(format: .base64)
        try check(try aes(.aesEncrypt, plaintext, base64Options) == base64)
        try check(try aes(.aesDecrypt, " \n" + base64 + "\n", base64Options) == plaintext)
        let fixtures = [
            ("abcdefghijklmnopqrstuvwx", "AES-192 · 中文", "55916985d0cd7a1c050027ca213e270d774be5d59c8ea106368d09c52f48d00c"),
            ("0123456789abcdef0123456789abcdef", "AES-256 · 🪴", "b3efa9565fd4d024891eee78c88ca525")
        ]
        for (key, text, ciphertext) in fixtures {
            let options = AESOptions(key: key, keyRule: .other)
            try check(try aes(.aesEncrypt, text, options) == ciphertext)
            try check(try aes(.aesDecrypt, ciphertext, options) == text)
        }
        print("PASS: AES-CBC/PKCS7 CryptoJS interoperability, 128/192/256-bit keys, Hex and Base64")

        let compatible = AESOptions(packageName: "abc", keyRule: .packageName)
        try check(try aes(.aesDecrypt, "200a8c817e3c331c7d5c5afff440c434", compatible) == "compatible key")
        try check(try aes(.aesEncrypt, "compatible key", compatible) == "200a8c817e3c331c7d5c5afff440c434")
        try check(try AESEngine.effectiveKey(AESOptions(packageName: "abcdefghijklmnopEXTRA", keyRule: .packageName)) == Data("abcdefghijklmnop".utf8))
        rejectsAES(hex, AESOptions(keyRule: .packageName), message: "包名")
        for (value, derived) in [("com.Example.App", "Y29tLmV4YW1wbGUu"), ("Foo", "Zm9v000000000000"), ("ÉCOLE", "6WNvbGU=00000000"), ("ä", "5A==000000000000")] {
            try check(try AESEngine.effectiveKey(AESOptions(channelName: value, keyRule: .channel)) == Data(derived.utf8))
        }
        let channel = AESOptions(channelName: "com.Example.App", keyRule: .channel)
        try check(try aes(.aesDecrypt, "271670eea14779c9a00adf98cab51c24", channel) == "channel sample")
        let utf8 = AESOptions(key: "中文密钥abcd", keyRule: .other)
        let utf8Cipher = try aes(.aesEncrypt, plaintext, utf8)
        try check(try aes(.aesDecrypt, utf8Cipher, utf8) == plaintext)
        // Same input must follow different reference operations for package and channel.
        let package = AESOptions(packageName: "Com.Example.App", keyRule: .packageName)
        let channelOptions = AESOptions(channelName: "Com.Example.App", keyRule: .channel)
        let other = AESOptions(packageName: "ignored", channelName: "ignored", keyRule: .other)
        try check(try AESEngine.effectiveKey(package) == Data("Com.Example.App0".utf8))
        try check(try AESEngine.effectiveKey(channelOptions) == Data("Y29tLmV4YW1wbGUu".utf8))
        try check(try AESEngine.effectiveKey(other) == Data(AESOptions.defaultKey.utf8))
        for (options, ciphertext) in [
            (package, "b03f064a48f939562ee735757a8082a6"),
            (other, "427523c035f73fcc4ab3c54bca593fbe"),
            (channelOptions, "ccc9d960ab95fe0cba01bf597e16ee69")
        ] {
            try check(try aes(.aesEncrypt, "scenario sample", options) == ciphertext)
            try check(try aes(.aesDecrypt, ciphertext, options) == "scenario sample")
        }
        print("PASS: separate Package/Channel/Other CryptoJS fixtures, case preservation, key padding and channel derivation")
        print("PASS: UTF-8 key byte lengths")

        for invalid in ["0", "gg", "0x1234", "éé"] { rejectsAES(invalid, message: "Hex") }
        rejectsAES("00", message: "16 字节的整数倍")
        rejectsAES(" \n", message: "Hex")
        rejectsAES("%%", base64Options, message: "Base64")
        rejectsAES("AA==", base64Options, message: "16 字节的整数倍")
        rejectsAES(hex, AESOptions(key: "short", keyRule: .other), message: "密钥当前为")
        rejectsAES(hex, AESOptions(packageName: "中文密钥", keyRule: .packageName), message: "ASCII")
        rejectsAES(hex, AESOptions(channelName: "渠道", keyRule: .channel), message: "Latin-1")
        rejectsAES(hex, AESOptions(keyRule: .channel), message: "渠道名")
        rejectsAES(hex, AESOptions(key: String(repeating: "a", count: 4097), keyRule: .other), message: "过长")
        rejectsAES(hex, AESOptions(iv: "short"), message: "IV 当前为")
        rejectsAES(hex, AESOptions(iv: "中文中文中文中文中文中文中文中文"), message: "IV 当前为")
        rejectsAES(String(repeating: "00", count: 16), message: "解密")
        rejectsAES("8ee897ba5d2097e288c6a49d8f26c56f", message: "UTF-8 文本")
        rejectsAES("", message: "输入")
        rejectsAES("", mode: .aesEncrypt, message: "输入")
        print("PASS: AES malformed encodings, block sizes, invalid keys/IVs, corrupt padding and binary plaintext")
    }
    static func main() throws {
        try testAES()
        let formatted = try run(.jsonPretty, #"{"z":1,"a":[true,null,"你好 👋"]}"#)
        precondition(formatted.contains("\n") && formatted.range(of: "\"a\"")!.lowerBound < formatted.range(of: "\"z\"")!.lowerBound)
        let compact = try run(.jsonCompact, formatted)
        precondition(compact == #"{"a":[true,null,"你好 👋"],"z":1}"#)
        for fragment in ["null", "true", "42", #""hello""#, "[1,2]"] {
            try check(try run(.jsonCompact, fragment) == fragment)
        }
        rejects(.jsonPretty, "{broken}")
        print("PASS: JSON objects, ordering, compaction, Unicode and scalar values")

        let text = "A + B / 中文?👋#%"
        let encoded = try run(.urlEncode, text)
        precondition(encoded.contains("%20") && encoded.contains("%2B") && encoded.contains("%E4"))
        try check(try run(.urlDecode, encoded) == text)
        try check(try run(.urlDecode, "a+b") == "a+b")
        rejects(.urlDecode, "%ZZ")
        print("PASS: RFC 3986 round trip, literal plus and invalid escapes")

        let base64 = try run(.base64Encode, text)
        try check(try run(.base64Decode, base64) == text)
        try check(try run(.base64Decode, "\n \(base64)\n") == text)
        rejects(.base64Decode, "%%%")
        rejects(.base64Decode, "////")
        print("PASS: Base64 Unicode round trip, whitespace and non-UTF-8 data")

        try check(try run(.seconds, "0").contains("1970-01-01 00:00:00.000"))
        try check(try run(.milliseconds, "1000").contains("Unix 秒    1"))
        try check(try run(.date, "1970-01-01T00:00:01Z").contains("Unix 毫秒  1000"))
        try check(try run(.seconds, "-0.5").contains("Unix 秒    -1"))
        try check(try run(.seconds, "0", zone: "Asia/Shanghai").contains("08:00:00.000"))
        for value in ["NaN", "infinity", "1e300", "invalid"] { rejects(.seconds, value) }
        rejects(.date, "not a date")
        print("PASS: epoch, milliseconds, ISO dates, negative fractions, zones and overflow")

        rejects(.jsonPretty, String(repeating: "x", count: 5_000_001))
        print("PASS: input size limit")
    }
}
